<?php

declare(strict_types=1);

namespace App\Mcp\Agent;

use Mcp\Server\Transport\BaseTransport;

/**
 * A server-side transport that drives the DI {@see \Mcp\Server} in-process for a fixed sequence
 * of JSON-RPC request frames and *keeps* the responses — where the shipped
 * {@see \Mcp\Server\Transport\InMemoryTransport} discards them ({@see \Mcp\Server\Transport\InMemoryTransport::send()}).
 *
 * The Protocol layer does not hand responses to {@see send()} for sessioned requests: it queues
 * them on the session's outgoing queue (only sessionless errors — parse errors, missing session —
 * go through {@see send()} immediately). So we drain both: the immediate buffer first, then the
 * outgoing queue per frame. The session id is generated by the server while it processes the
 * `initialize` frame and threaded into every subsequent frame via {@see $sessionId}.
 *
 * @extends BaseTransport<list<array<string, mixed>>>
 */
final class CapturingTransport extends BaseTransport
{
    /** @var list<array<string, mixed>> decoded JSON-RPC response frames, in the order produced */
    private array $captured = [];

    private ?string $immediate = null;

    /**
     * @param list<string> $frames raw JSON-RPC request frames, fed in order
     */
    public function __construct(private readonly array $frames)
    {
        parent::__construct();
    }

    public function send(string $data, array $context): void
    {
        $this->immediate = $data;
    }

    /**
     * @return list<array<string, mixed>>
     */
    public function listen(): array
    {
        foreach ($this->frames as $frame) {
            $this->immediate = null;
            $this->handleMessage($frame, $this->sessionId);

            if (null !== $this->immediate) {
                $this->captured[] = $this->decode($this->immediate);

                continue;
            }

            if (null !== $this->sessionId) {
                foreach ($this->getOutgoingMessages($this->sessionId) as $message) {
                    $this->captured[] = $this->decode($message['message']);
                }
            }
        }

        return $this->captured;
    }

    public function close(): void
    {
        // Drop the throwaway session created during initialize so the file store does not grow.
        $this->handleSessionEnd($this->sessionId);
        $this->sessionId = null;
    }

    /**
     * @return array<string, mixed>
     */
    private function decode(string $json): array
    {
        return json_decode($json, true, 512, \JSON_THROW_ON_ERROR);
    }
}
